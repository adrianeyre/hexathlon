/**
 * Writes the Attract Mode demo traces in `data/attract/`: one synthetic Input
 * Trace per built Event, mashing at 12 presses a second, with the ACTION
 * timing searched for so the demo makes a good, valid Attempt with the
 * current parameters. They are `source: synthetic`, so the replay harness
 * never treats them as parity targets.
 *
 * Run with `pnpm attract` after changing `data/events.json`; the tests fail
 * if a demo no longer makes a valid Mark.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runTrace } from '../calibration/harness.ts';
import { hurdlePositions } from '../src/sim/hurdles.ts';
import { EVENT_SIMS, SIM_PARAMS, eventStandard } from '../src/sim/registry.ts';

export type InputTrace = import('../calibration/types.ts').InputTrace;
export type TraceInput = import('../calibration/types.ts').TraceInput;
export type EventId = import('../src/sim/types.ts').EventId;

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Frames between run presses (12 a second), and how long each is held. */
const MASH_EVERY = 5;
const MASH_HOLD = 2;
/** Frames ACTION is held, for an angle near the middle of the window. */
const ACTION_HOLD = 29;
/** The High Jump's window is steeper, so ACTION is held longer. */
const HIGH_JUMP_HOLD = 40;
/** The Hurdles demo jumps when the next hurdle is this many pixels ahead. */
const HURDLE_LEAD = 34;

/** The Events with a demo, in the original's order. */
export const ATTRACT_EVENTS = (['sprint', 'longJump', 'javelin', 'hurdles', 'hammer', 'highJump'] as const);

/**
 * A trace that mashes from `mashFrom` to `mashTo`, and presses ACTION at
 * `actionAt` (if not null) for `ACTION_HOLD` frames.
 */
function planTrace(event: EventId, { mashFrom, mashTo, actionAt, frames, hold = ACTION_HOLD }: { mashFrom: number; mashTo: number; actionAt: number | null; frames: number; hold?: number; }): InputTrace {
  const inputs: TraceInput[] = [];
  for (let f = mashFrom, i = 0; f + MASH_HOLD < mashTo; f += MASH_EVERY, i++) {
    const action = i % 2 ? 'RUN_B' : 'RUN_A';
    inputs.push({ frame: f, player: 1, action, type: 'press' }, { frame: f + MASH_HOLD, player: 1, action, type: 'release' });
  }
  if (actionAt !== null) {
    inputs.push({ frame: actionAt, player: 1, action: 'ACTION', type: 'press' }, { frame: actionAt + hold, player: 1, action: 'ACTION', type: 'release' });
  }
  inputs.sort((a, b) => a.frame - b.frame || (a.type === 'release' ? -1 : 1));
  return {
    formatVersion: 1,
    id: `${event}/attract`,
    event,
    cycle: 1,
    players: 1,
    frames,
    source: 'synthetic',
    description: 'Attract Mode demo, generated by tools/make-attract-traces.js from the provisional parameters. Not captured from the original.',
    inputs,
  };
}

/**
 * Trim a trace to end the frame after its result.
 */
function trimmed(trace: InputTrace) {
  const sim = (EVENT_SIMS[trace.event] as import('../src/sim/types.ts').EventSim<any>);
  let state = sim.init({ cycle: trace.cycle, players: trace.players, attempt: 1, ...(trace.barHeight === undefined ? {} : { barHeight: trace.barHeight }) });
  for (let f = 0; f < trace.frames; f++) {
    state = sim.step(state, { frame: f, edges: trace.inputs.filter((i) => i.frame === f) });
    if (sim.getResult(state)) {
      const frames = f + 1;
      return { ...trace, frames, inputs: trace.inputs.filter((i) => i.frame < frames) };
    }
  }
  return trace;
}

/**
 * The best valid demo for an Event.
 */
export function makeAttractTrace(event: EventId): InputTrace {
  const sim = EVENT_SIMS[event];
  if (!sim) throw new Error(`no simulation for ${event}`);
  const frames = 1500;
  if (event === 'sprint') {
    // Wait for the start signal, then mash all the way.
    const from = SIM_PARAMS.sprint.startSignalFrame + 2;
    return trimmed(planTrace(event, { mashFrom: from, mashTo: frames, actionAt: null, frames }));
  }
  if (event === 'hurdles') return trimmed(hurdlesTrace(frames));
  if (event === 'highJump') {
    // One Attempt at the first Cycle's Standard, so the demo clears a bar worth seeing.
    const barHeight = eventStandard('highJump', 1).value;
    for (let actionAt = 30; actionAt < 1100; actionAt++) {
      const trace = { ...planTrace(event, { mashFrom: 0, mashTo: actionAt, actionAt, frames, hold: HIGH_JUMP_HOLD }), barHeight };
      if (runTrace(sim, trace)?.marks[0].outcome === 'valid') return trimmed(trace);
    }
    throw new Error('no valid demo found for highJump');
  }
  let best: InputTrace | null = null;
  let bestMark = -1;
  for (let actionAt = 60; actionAt < 1100; actionAt++) {
    // The Long Jump stops mashing at take-off; the throws keep mashing until release.
    const mashTo = event === 'longJump' ? actionAt : actionAt + ACTION_HOLD;
    const trace = planTrace(event, { mashFrom: 0, mashTo, actionAt, frames });
    const mark = runTrace(sim, trace)?.marks[0];
    if (mark?.outcome === 'valid' && mark.value !== null && mark.value > bestMark) {
      best = trace;
      bestMark = mark.value;
    }
  }
  if (!best) throw new Error(`no valid demo found for ${event}`);
  return trimmed(best);
}

/**
 * The Hurdles demo: mash from the start signal, and jump (a two-frame tap of
 * ACTION) whenever the next hurdle is `HURDLE_LEAD` pixels ahead.
 */
function hurdlesTrace(frames: number): InputTrace {
  const sim = (EVENT_SIMS.hurdles as import('../src/sim/types.ts').EventSim<any>);
  const base = planTrace('hurdles', { mashFrom: SIM_PARAMS.hurdles.startSignalFrame + 2, mashTo: frames, actionAt: null, frames });
  const hurdles = hurdlePositions(SIM_PARAMS.hurdles);
  const actions: TraceInput[] = [];
  let state = sim.init({ cycle: 1, players: 1 });
  for (let f = 0; f < frames && !sim.getResult(state); f++) {
    const edges = [...base.inputs, ...actions].filter((i) => i.frame === f);
    state = sim.step(state, { frame: f, edges });
    const ahead = hurdles[state.nextHurdle] - state.x;
    const lastAction = actions[actions.length - 1];
    if (state.phase === 'race' && state.jumpFrame === null && ahead < HURDLE_LEAD && (!lastAction || lastAction.frame <= f)) {
      actions.push({ frame: f + 1, player: 1, action: 'ACTION', type: 'press' }, { frame: f + 3, player: 1, action: 'ACTION', type: 'release' });
    }
  }
  const inputs = [...base.inputs, ...actions].sort((a, b) => a.frame - b.frame || (a.type === 'release' ? -1 : 1));
  return { ...base, inputs };
}

/** Path of an Event's demo, relative to the site root. @param event */
export const attractPath = (event: EventId) => `data/attract/${event}.trace.json`;

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const event of ATTRACT_EVENTS) {
    const trace = makeAttractTrace(event);
    const file = { $schema: '../../calibration/schema/input-trace.schema.json', ...trace };
    writeFileSync(join(ROOT, attractPath(event)), `${JSON.stringify(file, null, 2)}\n`);
    console.log(`${attractPath(event)}: ${trace.frames} frames`);
  }
}
