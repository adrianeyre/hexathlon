/** Glyph for characters the font doesn't cover. */
export const MISSING = '�';

/** A glyph as horizontal runs of lit pixels, so drawing needs few fillRects. */
export type GlyphRuns = readonly (readonly [x: number, y: number, width: number])[];

function toRuns(rows: readonly string[]): GlyphRuns {
  const runs: [number, number, number][] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (row[x] === '#') x++;
      runs.push([start, y, x - start]);
    }
  });
  return runs;
}

/** Glyph rows by character, for tests and tools. */
export const GLYPHS = (Object.freeze(GLYPH_ROWS) as Readonly<Record<string, readonly string[]>>);

const RUNS: Map<string, GlyphRuns> = new Map(Object.entries(GLYPH_ROWS).map(([ch, rows]) => [ch, toRuns(rows)]));

/**
 * The runs for one character, falling back to capitals then the missing glyph.
 */
export function glyphRuns(ch: string): GlyphRuns {
  return RUNS.get(ch) ?? RUNS.get(ch.toUpperCase()) ?? (RUNS.get(MISSING) as GlyphRuns);
}

/**
 * Width of a line of text in internal pixels (no trailing spacing).
 */
export function textWidth(text: string, scale: number = 1) {
  const chars = [...text].length;
  return chars === 0 ? 0 : (chars * ADVANCE - 1) * scale;
}
