/**
 * Service worker for offline play. It caches every file the game needs on
 * install, then serves them from the cache.
 *
 * VERSION is the commit SHA in a deployed build (`SW_VERSION` given to
 * `build.ts` by the deploy job), so each release gets a fresh cache and the old one is deleted when the new worker
 * activates. Locally it stays 'dev', and the worker goes to the network first
 * so edits show up on reload, using the cache only when offline.
 *
 * Paths are relative to this file, so the game works under a subpath.
 */

/** Filled in by `build.ts`: the cache version (the commit SHA when deployed, 'dev' locally) and the precache list. */
declare const __VERSION__: string;
declare const __ASSETS__: string[];

const VERSION = __VERSION__;
const CACHE = `hexathlon-${VERSION}`;

/** Everything the built page loads, generated by `build.ts` from the page itself, so it is always complete. */
const ASSETS: string[] = __ASSETS__;

const worker: any = self;

worker.addEventListener('install', (event: any) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // `reload` skips the HTTP cache so a new version never caches stale files.
      .then((cache) => cache.addAll(ASSETS.map((url) => new Request(url, { cache: 'reload' }))))
      .then(() => worker.skipWaiting()),
  );
});

worker.addEventListener('activate', (event: any) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('hexathlon-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => worker.clients.claim()),
  );
});

worker.addEventListener('fetch', (event: any) => {
  const request: Request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== worker.location.origin) return;
  const navigation = request.mode === 'navigate';
  const fromCache = () =>
    caches
      .open(CACHE)
      .then((cache) => cache.match(request, { ignoreSearch: navigation }).then((hit) => hit ?? (navigation ? cache.match('./') : undefined)));

  if (VERSION === 'dev') {
    // Development: always fresh, cache only as an offline fallback.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => fromCache().then((hit) => hit ?? Response.error())),
    );
    return;
  }
  event.respondWith(fromCache().then((hit) => hit ?? fetch(request)));
});

// A module, so its names stay out of the global scope of the other files.
export {};
